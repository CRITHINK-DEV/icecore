-- One-time sandbox setup for icecore integration tests and spikes.
-- Run as ACCOUNTADMIN on a sandbox account only. Replace <PUBLIC_KEY> with the CI user's RSA public key
-- (the body of rsa_key.pub without the BEGIN/END lines).
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ICECORE_SANDBOX;
CREATE SCHEMA IF NOT EXISTS ICECORE_SANDBOX.TELEMETRY;
CREATE SCHEMA IF NOT EXISTS ICECORE_SANDBOX.SPIKES;
CREATE EVENT TABLE IF NOT EXISTS ICECORE_SANDBOX.TELEMETRY.EVENTS;

-- Enterprise edition: route this database's telemetry to the sandbox event table.
ALTER DATABASE ICECORE_SANDBOX SET EVENT_TABLE = ICECORE_SANDBOX.TELEMETRY.EVENTS;
-- Standard edition: comment the line above and use the account-level setting instead
-- (this affects every database in the account, so only on a dedicated sandbox account):
-- ALTER ACCOUNT SET EVENT_TABLE = ICECORE_SANDBOX.TELEMETRY.EVENTS;

ALTER DATABASE ICECORE_SANDBOX SET LOG_LEVEL = INFO;
ALTER DATABASE ICECORE_SANDBOX SET TRACE_LEVEL = ALWAYS;

CREATE WAREHOUSE IF NOT EXISTS ICECORE_CI_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS ICECORE_CI;
GRANT USAGE ON WAREHOUSE ICECORE_CI_WH TO ROLE ICECORE_CI;
GRANT USAGE ON DATABASE ICECORE_SANDBOX TO ROLE ICECORE_CI;
GRANT USAGE ON SCHEMA ICECORE_SANDBOX.TELEMETRY TO ROLE ICECORE_CI;
GRANT OWNERSHIP ON SCHEMA ICECORE_SANDBOX.SPIKES TO ROLE ICECORE_CI COPY CURRENT GRANTS;
GRANT SELECT ON EVENT TABLE ICECORE_SANDBOX.TELEMETRY.EVENTS TO ROLE ICECORE_CI;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE ICECORE_CI;
-- S1 switches levels for its own session only (database levels are set above by ACCOUNTADMIN).
GRANT MODIFY SESSION LOG LEVEL ON ACCOUNT TO ROLE ICECORE_CI;
GRANT MODIFY SESSION TRACE LEVEL ON ACCOUNT TO ROLE ICECORE_CI;

CREATE USER IF NOT EXISTS ICECORE_CI_USER
  TYPE = SERVICE
  DEFAULT_ROLE = ICECORE_CI
  DEFAULT_WAREHOUSE = ICECORE_CI_WH
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE ICECORE_CI TO USER ICECORE_CI_USER;
